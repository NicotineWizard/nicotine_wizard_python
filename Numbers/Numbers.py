# Numbers (Integers)

print(2 + 3) # addition +
print(3 - 2) # subtraction -
print(2 * 3) # multiplaction *
print(3 // 8) # division / 
print(10 ** 12) # exponents **
print(2 + 3*4) # multiple operations

# Numbers (Floats)

print(0.1 + 0.1) # float addition
print(0.1 - 0.2) # float subtraction
print(2 * 0.1) # float multiplcation
print(0.4 // 0.1) # float division
print(0.2 ** 0.4) # float exponents
print(0.4 + 0.7*4) # float multiple operations

# Numbers I/F = (Floats and Integers)

print(1 + 2.0) # I/F addition
print(2 - 4.56) # I/F subtraction
print(3 * 2) # I/F multiplcation
print(0.8 // 1) # I/F division
print(1 ** 0.9) # I/F exponents
print(5 + 4.6*9) # I/F multiple operations

# Underscore in numbers = group digits together

